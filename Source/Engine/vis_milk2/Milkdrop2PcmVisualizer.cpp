// The preset saved with the set (Daxy, 2026-10-29). The render thread copies its current preset
// and lock into this snapshot (it is the only writer of m_szCurrentPresetFile, so the copy is
// whole); the plugin reads the snapshot under the lock. Paths inside the data folder are kept
// relative to it, so a set still finds its preset if the folder moves or the set goes to
// another PC with the same pack.
static std::wstring MDVST_RelativeToData(const std::wstring& path)
{
    std::wstring data = MDVST_DataDirectory();
    if (!data.empty() && data.back() != L'\\')
        data += L'\\';
    if (path.size() > data.size() && _wcsnicmp(path.c_str(), data.c_str(), data.size()) == 0)
        return path.substr(data.size());
    return path;
}

static void MDVST_PublishPreset()
{
    static DWORD last = 0;
    if (GetTickCount() - last < 250 || !mdvstAfterIntro.empty())
        return; // (during the app's opening screen the saved preset still counts)
    last = GetTickCount();
    std::wstring now = g_plugin.m_szCurrentPresetFile[0] ? MDVST_RelativeToData(g_plugin.m_szCurrentPresetFile) : std::wstring();
    std::lock_guard<std::mutex> lock(mdvstPresetMutex);
    mdvstPresetNow = now;
    mdvstLockedNow = g_plugin.m_bPresetLockedByUser;
}

bool MDVST_Engine_CurrentPreset(wchar_t* path, int maxChars, bool* locked)
{
    std::lock_guard<std::mutex> lock(mdvstPresetMutex);
    if (mdvstPresetNow.empty() || maxChars <= 0)
        return false;
    lstrcpynW(path, mdvstPresetNow.c_str(), maxChars);
    if (locked)
        *locked = mdvstLockedNow;
    return true;
}

void MDVST_Engine_SetStartPreset(const wchar_t* path, bool locked)
{
    std::lock_guard<std::mutex> lock(mdvstPresetMutex);
    mdvstPresetStart = path ? path : L"";
    mdvstLockedStart = locked;
}

bool MDVST_Engine_TakeStartPreset(wchar_t* path, int maxChars, bool* locked)
{
    std::lock_guard<std::mutex> lock(mdvstPresetMutex);
    if (mdvstPresetStart.empty() || maxChars <= 0)
        return false;
    std::wstring full = mdvstPresetStart;
    if (PathIsRelativeW(full.c_str()))
    {
        full = MDVST_DataDirectory();
        if (!full.empty() && full.back() != L'\\')
            full += L'\\';
        full += mdvstPresetStart;
    }
    *locked = mdvstLockedStart;
    mdvstPresetStart.clear();
    // Our presets' folder was presets\SwarmSynth until 2026-10-30, now presets\seethrew: a set or
    // app saved before then still finds its preset there.
    static const wchar_t kOldOurs[] = L"\\presets\\SwarmSynth\\";
    const size_t old = full.size() >= wcslen(kOldOurs) ? full.find(L"\\presets\\") : std::wstring::npos;
    if (GetFileAttributesW(full.c_str()) == INVALID_FILE_ATTRIBUTES && old != std::wstring::npos
        && _wcsnicmp(full.c_str() + old, kOldOurs, wcslen(kOldOurs)) == 0)
        full.replace(old, wcslen(kOldOurs), L"\\presets\\seethrew\\");
    // And the Life and Pixel Life presets moved into seethrew\Patches (same day, from SwarmSynth\Life,
    // Pixel Life and seethrew itself): the same file name there.
    const size_t name = full.find_last_of(L'\\');
    if (GetFileAttributesW(full.c_str()) == INVALID_FILE_ATTRIBUTES && name != std::wstring::npos)
    {
        std::wstring moved = MDVST_DataDirectory();
        if (!moved.empty() && moved.back() != L'\\')
            moved += L'\\';
        moved += L"presets\\seethrew\\Patches" + full.substr(name);
        if (GetFileAttributesW(moved.c_str()) != INVALID_FILE_ATTRIBUTES)
            full = moved;
    }
    if (GetFileAttributesW(full.c_str()) == INVALID_FILE_ATTRIBUTES)
        return false; // moved or deleted: the usual start-up preset instead
    if (mdvstIntroFirst.load() && g_plugin.m_bEnablePresetStartup
        && GetFileAttributesW(g_plugin.m_szPresetStartup) != INVALID_FILE_ATTRIBUTES
        && lstrcmpiW(full.c_str(), g_plugin.m_szPresetStartup) != 0)
    {
        // The app: the opening screen first, this preset after it (MDVST_AfterIntro).
        mdvstAfterIntro = full;
        mdvstAfterIntroLocked = *locked;
        mdvstIntroStarted = GetTickCount();
        mdvstIntroPlaying.store(true);
        return false;
    }
    lstrcpynW(path, full.c_str(), maxChars);
    return true;
}

void MDVST_Engine_SetIntroFirst(bool introFirst)
{
    mdvstIntroFirst.store(introFirst);
}

// Render thread, every frame while the opening screen plays before the saved preset: at normal
// speed (MDVST_Engine_Speed), no automatic switch, for one pour (8 s), then the saved preset blends
// in with its lock. A preset the user picks meanwhile wins.
static void MDVST_AfterIntro()
{
    if (mdvstAfterIntro.empty())
        return;
    if (lstrcmpiW(g_plugin.m_szCurrentPresetFile, g_plugin.m_szPresetStartup) != 0)
    {
        mdvstAfterIntro.clear(); // the user moved on
        mdvstIntroPlaying.store(false);
        return;
    }
    if (GetTickCount() - mdvstIntroStarted < 8000)
    {
        g_plugin.m_fNextPresetTime = g_plugin.GetTime() + 5.0f; // hold off the automatic switch
        return;
    }
    const std::wstring next = mdvstAfterIntro;
    mdvstAfterIntro.clear();
    mdvstIntroPlaying.store(false);
    g_plugin.LoadPreset(next.c_str(), 2.0f);
    g_plugin.m_bPresetLockedByUser = mdvstAfterIntroLocked;
}

void MDVST_Engine_PushAudio(const float* left, const float* right, int numFrames, int sampleRate)
{
    if (numFrames <= 0 || sampleRate <= 0 || left == nullptr)
        return;
    std::vector<float> interleaved((size_t)numFrames * 2);
    for (int i = 0; i < numFrames; ++i)
    {
        interleaved[(size_t)i * 2] = left[i];
        interleaved[(size_t)i * 2 + 1] = right ? right[i] : left[i];
    }
    WAVEFORMATEX wfx = {};
    wfx.wFormatTag = WAVE_FORMAT_IEEE_FLOAT;
    wfx.nChannels = 2;
    wfx.nSamplesPerSec = (DWORD)sampleRate;
    wfx.wBitsPerSample = 32;
    wfx.nBlockAlign = 8;
    wfx.nAvgBytesPerSec = wfx.nSamplesPerSec * wfx.nBlockAlign;
    SetAudioBuf(reinterpret_cast<const BYTE*>(interleaved.data()), (UINT32)numFrames, &wfx, false);
}
