unsigned __stdcall DoShaderPrecache(void* param) {

    // Give the render thread time to finish plugin and Direct3D initialization.
    for (int waited = 0; waited < 3000 && !shaderPrecacheCancel.load(); waited += 50)
        Sleep(50);
    if (shaderPrecacheCancel.load())
        return 0;

    HINSTANCE instance = (HINSTANCE)param;

    if (g_plugin.m_bShaderCaching && g_plugin.m_bShaderPrecachingAtStartup) {

        std::wstring cacheDir = MDVST_SHADERCACHE_DIR; // MDVST: was SUBDIR L"shadercache"
        std::wstring compiledListPath = cacheDir + L"\\cached.txt";

        //Incubo_ - Check if the shader cache folder is already in. If not, create it.
        std::error_code fsError; // MDVST: non-throwing overloads; a throw here ends the host process
        if (!std::filesystem::exists(cacheDir, fsError))
            std::filesystem::create_directory(cacheDir, fsError);
        //else
            //g_plugin.AddErrorNotif(L"Cannot create shadercache directory. Folder already exists or doesn't have permission to create.");

        // Abort if compiled.txt already exists, do this again if didn't precache shaders from precache.txt file accordingly.
        if (!g_plugin.m_bNeedsShaderReprecacheAtStartup)
            if (std::filesystem::exists(compiledListPath, fsError)) { // MDVST: non-throwing
                std::cerr << "Shader cache already exists, skipping precompilation\n";
                return -1;
            }

        // Open precompile.txt
        std::ifstream file(MDVST_PRECACHE_FILE); // MDVST: was "precache.txt"
        if (!file.is_open()) {
            g_plugin.AddErrorNotif(L"Failed to open precache.txt");
            return -1;
        }

        // Prepare output file for compiled shader list
        std::wofstream compiledList(compiledListPath);
        if (!compiledList.is_open()) {
            std::wstring msg = L"Failed to create " + compiledListPath;
            wchar_t* writableMsg = &msg[0];  // Get non-const pointer to internal buffer
            g_plugin.AddErrorNotif(writableMsg);
            return -1;
        }

        g_plugin.AddError(L"Precaching shaders...", INFINITE, ERR_SHADER_PRECACHE, false);

        int compiledShaders = 0;
        std::string line;
        auto start = std::chrono::high_resolution_clock::now();

        // Set UTF-8 locale for the output stream
        compiledList.imbue(std::locale(std::locale::empty(), new std::codecvt_utf8<wchar_t>));

        while (std::getline(file, line)) {
            if (shaderPrecacheCancel.load())
                break;

            // Skip BOM if present (UTF-8)
            if (!line.empty() && line[0] == '\xEF' && line[1] == '\xBB' && line[2] == '\xBF') {
                line.erase(0, 3);
            }

            // Convert UTF-8 to wide string properly
            std::wstring wLine;
            if (!line.empty()) {
                int size_needed = MultiByteToWideChar(CP_UTF8, 0, &line[0], (int)line.size(), NULL, 0);
                wLine.resize(size_needed);
                MultiByteToWideChar(CP_UTF8, 0, &line[0], (int)line.size(), &wLine[0], size_needed);
            }

            // Trim whitespace
            wLine.erase(0, wLine.find_first_not_of(L" \t"));
            wLine.erase(wLine.find_last_not_of(L" \t") + 1);

            // Skip empty lines or comments
            if (wLine.empty() || wLine[0] == L'#') continue;

            // Check for wildcard
            if (!wLine.empty() && wLine.back() == L'*') {
                std::wstring dirPath = wLine.substr(0, line.length() - 1); // Remove '*'
                if (std::filesystem::exists(dirPath)) {
                    for (const auto& entry : std::filesystem::directory_iterator(dirPath)) {
                        if (shaderPrecacheCancel.load())
                            break;
                        if (entry.is_regular_file()) {
                            PrecachePresetShaders(entry.path().wstring(), compiledList, compiledShaders);
                        }
                    }
                }
            }
            else {
                PrecachePresetShaders(wLine, compiledList, compiledShaders);
            }
        }

        file.close();
        compiledList.close();
        if (shaderPrecacheCancel.load())
            return 0;

        auto end = std::chrono::high_resolution_clock::now();
        auto duration = std::chrono::duration<double>(end - start); // fractional seconds
        std::wstringstream ss;
        ss << std::fixed << std::setprecision(2) << duration.count();

        std::wstring message = L"Precached " + std::to_wstring(compiledShaders)
            + L" shaders. Finished in " + ss.str() + L" seconds.";

        wchar_t szMessage[256];
        wcsncpy_s(szMessage, message.c_str(), _TRUNCATE);
        g_plugin.ClearErrors(ERR_SHADER_PRECACHE);
        g_plugin.AddError(szMessage, 5, ERR_SHADER_PRECACHE, false);
        g_plugin.m_bNeedsShaderReprecacheAtStartup = false; // Finished precaching shaders, no need to reprecache again at startup.
    }
    return 0;
}

void PrecachePresetShaders(std::wstring& wLine, std::wofstream& compiledList, int& compiledShaders) {
    wchar_t szFile[512];
    // Treat anything without a drive letter as relative
    if (wLine.find(L":\\") == std::wstring::npos) {
        lstrcpyW(szFile, g_plugin.m_szBaseDir);
        lstrcatW(szFile, wLine.c_str());
    }
    else {
        lstrcpyW(szFile, wLine.c_str());
    }

    // Compile the shader
    if (std::filesystem::exists(std::filesystem::path(szFile))) {

        //Checks for MILKDROP_PRESET_VERSION and PSVERSION if it's a preset that contains shaders.
        std::ifstream presetFile(szFile);
        if (presetFile.is_open()) {
            std::string line;
            bool checkedShader = false;
            while (std::getline(presetFile, line)) {
                if (line.find("MILKDROP_PRESET_VERSION") != std::string::npos ||
                    line.find("PSVERSION") != std::string::npos)
                {
                    checkedShader = true;
                    break;
                }
            }
            presetFile.close();

            if (!checkedShader)
                return; // Skip non-shader presets
        }

        auto start = std::chrono::high_resolution_clock::now();
        g_plugin.CompilePresetShadersToFile(szFile);
        auto end = std::chrono::high_resolution_clock::now();
        auto durationMs = std::chrono::duration_cast<std::chrono::milliseconds>(end - start).count();
        std::wstring warn = L" ";
        if (durationMs > 1000) {
            warn = L"!";
        }
        compiledList << warn << std::setw(8) << std::setfill(L' ') << durationMs << " " << szFile << std::endl;
        compiledShaders++;
    }
}

void DeleteShaderCacheDirectory()
{
    std::wstring cacheDir = MDVST_SHADERCACHE_DIR; // MDVST: was SUBDIR L"shadercache"

    std::error_code fsError; // MDVST: non-throwing
    if (std::filesystem::exists(cacheDir, fsError)) {
        try {
            std::filesystem::remove_all(cacheDir);
            printf("Shader cache directory deleted: %S\n", cacheDir.c_str());
        }
        catch (const std::filesystem::filesystem_error& ex) {
            printf("Error deleting shader cache directory: %s\n", ex.what());
        }
    }
}

