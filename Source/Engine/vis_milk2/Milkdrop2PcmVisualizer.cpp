// Back into the editor after full screen / stretch, or out of the parked state. False if there
// is no editor any more.
static std::atomic<bool> mdvstParked { false };

static bool MDVST_ReturnToHost(HWND hwnd)
{
    HWND host = mdvstHost.load();
    if (host == nullptr || !IsWindow(host))
        return false;
    SetWindowLongW(hwnd, GWL_STYLE, WS_CHILD | WS_VISIBLE | WS_CLIPSIBLINGS);
    SetWindowLongW(hwnd, GWL_EXSTYLE, WS_EX_NOPARENTNOTIFY);
    SetParent(hwnd, host);
    MDVST_FillHost(hwnd);
    ShowWindow(hwnd, SW_SHOWNA);
    mdvstParked = false;
    return true;
}

// Parked: the plugin's window closed (Daxy, 2026-10-29: reopening should bring back the same
// visuals, preset, menus and all). The render window leaves the editor, hidden, and the render
// loop stops drawing until a new editor takes it back (MDVST_Engine_Start). Render thread only.
static void MDVST_Park(HWND hwnd)
{
    ShowWindow(hwnd, SW_HIDE);
    SetWindowLongW(hwnd, GWL_STYLE, WS_POPUP);
    SetWindowLongW(hwnd, GWL_EXSTYLE, WS_EX_TOOLWINDOW); // no taskbar button while hidden
    SetParent(hwnd, nullptr);
    mdvstParked = true;
}

