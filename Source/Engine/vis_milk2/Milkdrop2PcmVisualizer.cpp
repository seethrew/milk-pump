// MDVST: the window inside a DAW (Daxy, 2026-10-29).
//
// A saved size that fills (nearly) the whole screen, a maximized or full-screen window remembered
// from last time, or a position on a monitor that is no longer there, opens instead as a 960x540
// picture centred on the monitor the host is on. Full screen stays one key away (double-click).
static void MDVST_SensibleWindowRect()
{
    HWND host = GetForegroundWindow();
    HMONITOR mon = host ? MonitorFromWindow(host, MONITOR_DEFAULTTOPRIMARY)
                        : MonitorFromPoint(POINT { 0, 0 }, MONITOR_DEFAULTTOPRIMARY);
    MONITORINFO mi = { sizeof(mi) };
    GetMonitorInfoW(mon, &mi);
    const RECT wa = mi.rcWork;
    const int waW = wa.right - wa.left, waH = wa.bottom - wa.top;

    RECT saved = { g_plugin.m_nWindowPosX, g_plugin.m_nWindowPosY,
                   g_plugin.m_nWindowPosX + g_plugin.m_nWindowWidth, g_plugin.m_nWindowPosY + g_plugin.m_nWindowHeight };
    const bool tooBig = g_plugin.m_nWindowWidth > waW * 9 / 10 || g_plugin.m_nWindowHeight > waH * 9 / 10;
    const bool tooSmall = g_plugin.m_nWindowWidth < 200 || g_plugin.m_nWindowHeight < 120;
    const bool offScreen = MonitorFromRect(&saved, MONITOR_DEFAULTTONULL) == nullptr;
    if (!tooBig && !tooSmall && !offScreen)
        return;

    RECT rc = { 0, 0, 960, 540 };
    AdjustWindowRect(&rc, WS_OVERLAPPEDWINDOW, FALSE);
    const int w = rc.right - rc.left < waW ? rc.right - rc.left : waW;
    const int h = rc.bottom - rc.top < waH ? rc.bottom - rc.top : waH;
    g_plugin.m_nWindowWidth = w;
    g_plugin.m_nWindowHeight = h;
    g_plugin.m_nWindowPosX = wa.left + (waW - w) / 2;
    g_plugin.m_nWindowPosY = wa.top + (waH - h) / 2;
}

// Floats the window above the host while the host is the app in use, as a plugin's own window
// would, and lets it drop behind other apps. Without this, clicking Live put Live's full-size
// window over it with nothing to click to get it back. A window can't be owned by Live's window
// from this thread (that would tie Live's UI to the render thread), so the order is set by hand,
// only when the foreground app changes. Full screen, borderless and F7 (always on top) keep their
// own behaviour.
static int mdvstHostActive = -1; // -1 = not known (reset whenever another mode is in charge)

static void MDVST_FloatAboveHost(HWND hwnd)
{
    static DWORD lastCheck = 0;
    const DWORD now = GetTickCount();
    if (now - lastCheck < 150)
        return;
    lastCheck = now;

    if (fullscreen || stretch || borderless || g_plugin.m_bAlwaysOnTop || g_plugin.m_bDesktopMode || IsIconic(hwnd))
    {
        mdvstHostActive = -1;
        return;
    }
    HWND fg = GetForegroundWindow();
    if (fg == nullptr || fg == hwnd)
        return;
    DWORD pid = 0;
    GetWindowThreadProcessId(fg, &pid);
    const int hostActive = pid == GetCurrentProcessId() ? 1 : 0;
    if (hostActive == mdvstHostActive)
        return;
    mdvstHostActive = hostActive;
    const UINT flags = SWP_NOMOVE | SWP_NOSIZE | SWP_NOACTIVATE;
    if (hostActive)
        SetWindowPos(hwnd, HWND_TOPMOST, 0, 0, 0, 0, flags);
    else
    {
        SetWindowPos(hwnd, HWND_NOTOPMOST, 0, 0, 0, 0, flags);
        SetWindowPos(hwnd, fg, 0, 0, 0, 0, flags); // just behind the app now in use
    }
}

