void ResizeBeatDrop(int newWidth, int newHeight)
{
	// Client window size
	int width  = 640;
	int height = 360;
	// If the window is square - 512x512, otherwise 640x360
	if (newWidth == newHeight) {
		width  = 512;
		height = 512;
	}
	HWND hw = FindWindowA("Direct3DWindowClass", MDVST_WINDOW_TITLE_A); // MDVST: our name
	// Client to window
	RECT rc;
	SetRect(&rc, 0, 0, width, height);
	AdjustWindowRect(&rc, WS_OVERLAPPEDWINDOW, false);
	width = rc.right - rc.left;
	height = rc.bottom - rc.top;
	// Resize but do not move
	SetWindowPos(hw, NULL, 0, 0, width, height, SWP_NOMOVE | SWP_NOACTIVATE | SWP_NOZORDER);
}

unsigned __stdcall CreateWindowAndRun(void* data) {
	HINSTANCE instance = (HINSTANCE)data;

#ifdef DEBUG
	_CrtSetDbgFlag(_CRTDBG_ALLOC_MEM_DF | _CRTDBG_LEAK_CHECK_DF);
	_CrtSetBreakAlloc(60);
#endif

	// Use per-monitor DPI awareness where the OS provides it, while retaining
	// a Vista-compatible fallback without an app-local shcore/API-set DLL.
	EnableBestAvailableDpiAwareness();

	// Register the windows class
	WNDCLASSW wndClass;
	wndClass.style = CS_DBLCLKS;
	wndClass.lpfnWndProc = StaticWndProc;
	wndClass.cbClsExtra = 0;
	wndClass.cbWndExtra = 0;
	wndClass.hInstance = instance;
	wndClass.hIcon = LoadIconW(instance, MAKEINTRESOURCEW(IDI_PLUGIN_ICON));
	wndClass.hCursor = LoadCursor(NULL, IDC_ARROW);
	wndClass.hbrBackground = (HBRUSH)GetStockObject(BLACK_BRUSH);
	wndClass.lpszMenuName = NULL;
	wndClass.lpszClassName = L"Direct3DWindowClass";

	if (!RegisterClassW(&wndClass)) {
		DWORD dwError = GetLastError();
		if (dwError != ERROR_CLASS_ALREADY_EXISTS) {
			return 0;
		}
	}

	// SPOUT
	// Make the window a fixed size
    // The sender resolution is independent - see SpoutWidth/SpoutHeight below
	int windowWidth = g_plugin.m_nWindowWidth; // standalone version 1280x720
	int windowHeight = g_plugin.m_nWindowHeight;

	RECT rc;
	SetRect(&rc, 0, 0, windowWidth, windowHeight);
	AdjustWindowRect(&rc, WS_OVERLAPPEDWINDOW, false);

	// SPOUT
	// Centre on the desktop work area
	//int WindowPosLeft = 0;
	//int WindowPosTop = 0;
	//RECT WorkArea;
	//SystemParametersInfo(SPI_GETWORKAREA, 0, (LPVOID)&WorkArea, 0);
	//WindowPosLeft += ((WorkArea.right - WorkArea.left) - windowWidth) / 2;
	//WindowPosTop += ((WorkArea.bottom - WorkArea.top) - windowHeight) / 2;

	// SPOUT
	// Remove minimize and maximize
	//DWORD dwStyle = (WS_OVERLAPPED | WS_CAPTION | WS_SYSMENU | WS_THICKFRAME);

	// ===============================================
	// Enumerate other instances of BeatDrop to increment the title
	WCHAR beatdroptitle[256]; 
	lstrcpyW(beatdroptitle, MDVST_WINDOW_TITLE); // default render window title. MDVST: our name
	// printf("Number of existing beatdrops (%d)\n", nBeatDrops);
    bool freeTitleFound = false;
    nBeatDrops = 0;

    while (!freeTitleFound && nBeatDrops < 100) {
        if (nBeatDrops == 0) {
            lstrcpyW(beatdroptitle, MDVST_WINDOW_TITLE); // MDVST: our name
        }
        else {
            swprintf_s(beatdroptitle, MDVST_WINDOW_TITLE L" (%d)", nBeatDrops + 1); // MDVST: our name
        }

        // Check if a window with this title already exists
        HWND existing = FindWindowW(L"Direct3DWindowClass", beatdroptitle);
        if (existing != NULL) {
            nBeatDrops++;
            // Try next title
        }
        else {
            // No window with this title, so we can use it
            printf("New title [%S]\n", beatdroptitle);
            freeTitleFound = true;
        }
	}
	// ===============================================

#ifdef MDVST_PLUGIN
    MDVST_SensibleWindowRect(); // MDVST: open as a window, not screen-sized (Daxy, 2026-10-29)
    mdvstHostActive = -1;
    mdvstParked = false;
#endif

    auto createRenderWindow = [&]() -> HWND {
#ifdef MDVST_PLUGIN
        // MDVST: inside the plugin's window when it handed one over, filling it.
        HWND host = mdvstHost.load();
        RECT hostRect;
        if (host != nullptr && IsWindow(host) && GetClientRect(host, &hostRect))
            return CreateWindowExW(WS_EX_NOPARENTNOTIFY, L"Direct3DWindowClass", beatdroptitle,
                                   WS_CHILD | WS_VISIBLE | WS_CLIPSIBLINGS, 0, 0,
                                   hostRect.right > 0 ? hostRect.right : 1, hostRect.bottom > 0 ? hostRect.bottom : 1,
                                   host, NULL, instance, 0);
#endif
        return CreateWindowW(
	        L"Direct3DWindowClass",
			// ===========================
	        // L"BeatDrop Music Visualizer",
			beatdroptitle,
			// ===========================
	        WS_OVERLAPPEDWINDOW, // SPOUT
			//dwStyle,
			//WindowPosLeft, // SPOUT
			//WindowPosTop,
			// CW_USEDEFAULT,
			// CW_USEDEFAULT,
			//(rc.right - rc.left),
	        //(rc.bottom - rc.top),
	        g_plugin.m_nWindowPosX,
	        g_plugin.m_nWindowPosY,
	        g_plugin.m_nWindowWidth,
	        g_plugin.m_nWindowHeight,
	        0,
	        NULL,
	        instance,
	        0);
    };

    // Create the render window
    HWND hwnd = createRenderWindow();
	// ====================================================

    if (!hwnd) {
        DWORD dwError = GetLastError();
#ifdef MDVST_PLUGIN
        thread = nullptr; // MDVST: so IsRunning() reports the failure
        threadId = 0;
#endif
        return 0;
    }
#ifdef MDVST_PLUGIN
    mdvstRenderWindow = hwnd; // MDVST: for MDVST_Engine_HostResized
#endif

    if (!icon) {
        icon = LoadIconW(instance, MAKEINTRESOURCEW(IDI_PLUGIN_ICON));
    }

    SendMessageW(hwnd, WM_SETICON, ICON_BIG, (LPARAM) icon);
    SendMessageW(hwnd, WM_SETICON, ICON_SMALL, (LPARAM) icon);

    ShowWindow(hwnd, SW_SHOW);

    if (g_plugin.m_bAlwaysOnTop)
        g_plugin.ToggleAlwaysOnTop(hwnd);

	unsigned int frame = 0;

	// SPOUT - defaults if no GUI
    // Change the values here to set the fixed sender size
    RECT clientRect;
    GetClientRect(hwnd, &clientRect);
    unsigned int SpoutWidth = clientRect.right - clientRect.left;
    unsigned int SpoutHeight = clientRect.bottom - clientRect.top;

    // Set to windowWidth/windowHeight for a variable sender size
    // See milkDropfs.cpp RenderFrame - change to SendDX9surface(back_buffer, true); 
    // SpoutWidth = windowWidth;
    // SpoutHeight = windowHeight;

	unsigned int SpoutWidthOld = 0;
	unsigned int SpoutHeightOld = 0;
	// Read values if UI is open
	SpoutWidthOld = SpoutWidth;
	SpoutHeightOld = SpoutHeight;

    //Moved to StartThreads().
	//g_plugin.PluginPreInitialize(0, 0);

    // SPOUT
	// InitD3d(hwnd, windowWidth, windowHeight);
	InitD3d(hwnd, SpoutWidth, SpoutHeight);

	g_plugin.PluginInitialize(
		pD3DDevice,
		&d3dPp,
		hwnd,
		// windowWidth,
		// windowHeight);
		SpoutWidth,
		SpoutHeight);

    if (g_plugin.m_bFullscreenOnStartup && !g_plugin.m_bFullscreenStretchOnStartup && !g_plugin.m_bBorderlessOnStartup && pD3DDevice != nullptr)
        ToggleFullScreen(hwnd);
    if (!g_plugin.m_bFullscreenOnStartup && g_plugin.m_bFullscreenStretchOnStartup && !g_plugin.m_bBorderlessOnStartup && pD3DDevice != nullptr)
        ToggleStretch(hwnd);
    if (!g_plugin.m_bFullscreenOnStartup && !g_plugin.m_bFullscreenStretchOnStartup && g_plugin.m_bBorderlessOnStartup && pD3DDevice != nullptr)
        ToggleBorderlessWindow(hwnd);

    MSG msg;
    msg.message = WM_NULL;

    PeekMessage(&msg, NULL, 0U, 0U, PM_NOREMOVE);
    while (WM_QUIT != msg.message) {
        if (g_plugin.m_bDesktopMode && !intentionalWindowClose.load() && !IsWindow(hwnd))
            desktopWindowDestroyed = true;

        if (desktopWindowDestroyed.exchange(false)) {
            HWND replacement = createRenderWindow();
            if (!replacement) {
                PostQuitMessage(0);
                continue;
            }

            SendMessageW(replacement, WM_SETICON, ICON_BIG, (LPARAM)icon);
            SendMessageW(replacement, WM_SETICON, ICON_SMALL, (LPARAM)icon);

            g_plugin.PrepareForExternalDeviceReset();
            d3dPp.hDeviceWindow = replacement;
            g_plugin.ReplaceRenderWindow(replacement);
            const HRESULT resetResult = pD3DDevice->Reset(&d3dPp);
            if (FAILED(resetResult)) {
                intentionalWindowClose = true;
                DestroyWindow(replacement);
                PostQuitMessage(0);
                continue;
            }

            g_plugin.RestoreAfterExternalDeviceReset();
            hwnd = replacement;
            g_plugin.ToggleDesktopMode(hwnd, true);
            g_plugin.StartDesktopModeRecoveryTimers(hwnd);
        }

        if (PeekMessage(&msg, NULL, 0U, 0U, PM_REMOVE) != 0) {
            if (!HandleWebcamOpacityDialogMessage(&msg)) {
                TranslateMessage(&msg);
                DispatchMessage(&msg);
            }
        }
        else {
#ifdef MDVST_PLUGIN
            if (mdvstParked.load()) // MDVST: window closed: no drawing, almost no CPU
            {
                MsgWaitForMultipleObjects(0, nullptr, FALSE, 50, QS_ALLINPUT);
                frame++;
                continue;
            }
            if (!MDVST_IsEmbedded(hwnd))
                MDVST_FloatAboveHost(hwnd); // MDVST: a free window stays above Live while Live is in use
            MDVST_AfterIntro(); // MDVST: the app's opening screen, then its saved preset
            MDVST_PublishPreset(); // MDVST: for the set's saved state
            MDVST_ShowPendingMessage(); // MDVST: "Speed 1/2", "HQ on" from the plugin
#endif
            GetAudioBuf(pcmLeftIn, pcmRightIn, SAMPLE_SIZE);
            RenderFrame();

		}
		frame++;
		////////////////////////////////////////////////////////////////////////////////////////////////
    }

    // The precache worker calls into the plugin and must finish before plugin
    // state and Direct3D resources are torn down.
    CloseWebcamOpacityDialog();
    StopShaderPrecacheThread();
    g_plugin.MyWriteConfig();
    g_plugin.PluginQuit();

    DeinitD3d();

#ifdef MDVST_PLUGIN
    // MDVST: the window goes with this thread; destroy it here, while the plugin's wait still
    // pumps messages, rather than at thread exit.
    mdvstRenderWindow = nullptr;
    if (IsWindow(hwnd))
        DestroyWindow(hwnd);
#endif
    thread = nullptr;
    threadId = 0;

    return 1;
}

